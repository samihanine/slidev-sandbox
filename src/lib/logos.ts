export type Logo = { title: string; hex: string; path: string };

/** By slug (`github`) and by simplified title (`nodejs`, `vuejs`). */
export const LOGOS = new Map<string, Logo>();
for (const icon of LIST) {
  const logo = { title: icon.title, hex: `#${icon.hex}`, path: icon.path };
  LOGOS.set(icon.slug, logo);
  LOGOS.set(icon.title.toLowerCase().replace(/[^a-z0-9]/g, ""), logo);
}
